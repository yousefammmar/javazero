public class Main {
    public static void main(String[] args) {
        int i = 300;
        System.out.println((byte) i);
        System.out.println((byte) -129);
        System.out.println((byte) 128);
        System.out.println((short) 70000);
        System.out.println((short) -32769);
        System.out.println((char) 65);
        System.out.println((char) 65601);
        System.out.println((int) (char) -1);
        System.out.println((int) (byte) 200);
        System.out.println((char) (byte) -1 + 0);
        System.out.println((short) (char) 65535);
        long l = 0x1_2345_6789L;
        System.out.println((int) l);
        System.out.println((short) l);
        System.out.println((byte) l);
        System.out.println((char) l + "|");
        System.out.println((int) 3.99);
        System.out.println((int) -3.99);
        System.out.println((int) 1e20);
        System.out.println((int) -1e20);
        System.out.println((int) Double.NaN);
        System.out.println((long) 1e30);
        System.out.println((long) -1e30);
        System.out.println((long) Double.NaN);
        System.out.println((byte) 300.7);
        System.out.println((byte) 1e10);
        System.out.println((short) 1e10);
        System.out.println((char) 1e10 + 0);
        System.out.println((char) 66.9);
        System.out.println((int) Float.POSITIVE_INFINITY);
        System.out.println((long) Float.NEGATIVE_INFINITY);
        System.out.println((float) 1.1);
        System.out.println((double) 1.1f);
        System.out.println((float) 0.1 == 0.1);
        System.out.println(0.1f == 0.1);
        System.out.println((double) 16777217);
        System.out.println((float) 16777217);
        System.out.println((float) 123456789);
        System.out.println((double) 123456789L);
        System.out.println((float) Long.MAX_VALUE);
        System.out.println((double) Long.MAX_VALUE);
        System.out.println((long) (double) Long.MAX_VALUE);
        System.out.println((float) 1e40);
        System.out.println((float) 1e-50);
        System.out.println((float) Double.MAX_VALUE);
        System.out.println((double) Float.MAX_VALUE);
        System.out.println((double) Float.MIN_VALUE);
        int big = 123456789;
        float f = big;
        System.out.println(f);
        System.out.println((int) f);
        long lg = 1234567890123456789L;
        double d = lg;
        System.out.println(d);
        System.out.println((long) d);
        System.out.println(lg - (long) d);
        char c = 'x';
        int ci = c;
        long cl = c;
        float cf = c;
        double cd = c;
        System.out.println(ci + " " + cl + " " + cf + " " + cd);
        byte b = 10;
        short s = b;
        System.out.println(s);
        final int k = 100;
        byte kb = k;
        char kc = k;
        System.out.println(kb + " " + kc);
    }
}
