public class Main {
    public static void main(String[] args) {
        char c = 'a';
        c++;
        System.out.println(c);
        System.out.println(c + 1);
        System.out.println((char) (c + 1));
        System.out.println("" + c + 1);
        System.out.println(c + 1 + "");
        System.out.println('a' + 'b');
        System.out.println("" + 'a' + 'b');
        System.out.println('a' + 'b' + "c");
        System.out.println("c" + 'a' + 'b');
        System.out.println("c" + ('a' + 'b'));
        System.out.println((char) ('a' + 2));
        System.out.println('a' + 2);
        char d = 'A';
        d += 2;
        System.out.println(d);
        d *= 1;
        System.out.println(d);
        d -= 1;
        System.out.println(d);
        d = (char) (d + 32);
        System.out.println(d);
        char e = 'z';
        e++;
        System.out.println(e + " " + (int) e);
        char f = '0';
        int digit = f - '0';
        System.out.println(digit);
        for (char ch = 'a'; ch <= 'f'; ch++) System.out.print(ch);
        System.out.println();
        for (char ch = 'F'; ch >= 'A'; ch -= 2) System.out.print(ch + ",");
        System.out.println();
        char[] arr = new char[3];
        System.out.println((int) arr[0]);
        arr[0] = 'h'; arr[1] = 105; arr[2] = (char) 33;
        System.out.println(arr);
        System.out.println(new String(arr));
        System.out.println(String.valueOf(arr));
        System.out.println("arr=" + String.valueOf(arr));
        System.out.println('A' + "" + '\t' + "|" + '\\' + '\'' + '"');
        System.out.println((int) '\n' + " " + (int) '\r' + " " + (int) '\0' + " " + (int) '\t');
        System.out.println('a' < 'b');
        System.out.println('a' == 97);
        System.out.println((char) 97 == 'a');
        char up = (char) ('q' - 'a' + 'A');
        System.out.println(up);
        System.out.println(Character.toUpperCase('q') + "" + Character.toLowerCase('Q'));
        System.out.println(Character.toUpperCase('q') + Character.toLowerCase('Q'));
        int x = 'a' * 2;
        System.out.println(x);
        System.out.println((char) 0x263A);
        System.out.println(Character.MAX_VALUE + 0);
        System.out.println(Character.MIN_VALUE + 0);
        long t = 'a' + 1L;
        System.out.println(t);
        double dd = 'a' / 2.0;
        System.out.println(dd);
        String s = "hello";
        int sum = 0;
        for (char ch : s.toCharArray()) sum += ch;
        System.out.println(sum);
        StringBuilder sb = new StringBuilder();
        sb.append('a').append((char) 98).append(99).append('d' + 1);
        System.out.println(sb);
        char shift = 'x';
        shift += 5;
        System.out.println((int) shift);
        short sh = 5;
        sh += 'a';
        System.out.println(sh);
        System.out.println(c > 'a' ? 'Y' : 'N');
        System.out.println(true ? 'a' : 0);
        int zero = 0;
        System.out.println(true ? 'a' : zero);
    }
}
