public class Main {
    public static void main(String[] args) {
        int a = 0b1100, b = 0b1010;
        System.out.println(a & b);
        System.out.println(a | b);
        System.out.println(a ^ b);
        System.out.println(~a);
        System.out.println(~0);
        System.out.println(~-1);
        System.out.println(-8 >> 1);
        System.out.println(-8 >>> 1);
        System.out.println(-8 >> 33);
        System.out.println(-8 >>> 33);
        System.out.println(8 << 31);
        System.out.println(1 << 31);
        System.out.println(1 << 32);
        System.out.println(1 << -1);
        System.out.println(1 << 30 << 1);
        System.out.println(-1 >>> 31);
        System.out.println(-1 >>> 0);
        System.out.println(Integer.MIN_VALUE >> 31);
        System.out.println(Integer.MIN_VALUE >>> 31);
        System.out.println(5 >> 1 << 1);
        long l = -8L;
        System.out.println(l >> 1);
        System.out.println(l >>> 1);
        System.out.println(l >>> 60);
        System.out.println(l >> 65);
        System.out.println(1L << 63);
        System.out.println(1L << 64);
        System.out.println(1L << 32);
        System.out.println(1 << 32L);
        System.out.println(~l);
        System.out.println(0xFFL & -1);
        System.out.println(0xFF & -1);
        System.out.println((byte) 0xF0 >> 2);
        System.out.println((byte) 0xF0 >>> 2);
        System.out.println(((byte) 0xF0 & 0xFF) >> 2);
        System.out.println((byte) -16 >>> 28);
        byte bb = (byte) 0x9A;
        System.out.println(bb + " " + (bb & 0xFF) + " " + Integer.toHexString(bb) + " " + Integer.toHexString(bb & 0xFF));
        System.out.println(Integer.toBinaryString(-1));
        System.out.println(Integer.toBinaryString(5));
        System.out.println(Integer.toBinaryString(-8 >>> 28));
        System.out.println(Long.toBinaryString(5L << 33));
        System.out.println(Long.toHexString(-1L));
        System.out.println(Integer.toHexString(0xCAFE << 16));
        System.out.println(Integer.toOctalString(-1));
        int flags = 0;
        flags |= 1 << 3;
        flags |= 1 << 0;
        System.out.println(flags);
        flags &= ~(1 << 3);
        System.out.println(flags);
        flags ^= 0b111;
        System.out.println(flags);
        System.out.println((flags & (1 << 2)) != 0);
        int v = 0x12345678;
        int swapped = (v << 24) | ((v & 0xFF00) << 8) | ((v >>> 8) & 0xFF00) | (v >>> 24);
        System.out.println(Integer.toHexString(swapped));
        System.out.println(Integer.toHexString(Integer.reverseBytes(v)));
        System.out.println(Integer.rotateLeft(v, 8) == ((v << 8) | (v >>> 24)));
        System.out.println(Integer.bitCount(v) + " " + Long.bitCount(-1L));
        System.out.println(Integer.highestOneBit(100) + " " + Integer.lowestOneBit(100));
        System.out.println(Integer.numberOfLeadingZeros(1) + " " + Integer.numberOfTrailingZeros(8) + " " + Integer.numberOfLeadingZeros(0));
        System.out.println(Integer.reverse(1));
        System.out.println(true & false | true ^ true);
        int x = 5, y = 7;
        x ^= y; y ^= x; x ^= y;
        System.out.println(x + " " + y);
        System.out.println(1 + 2 << 3);
        System.out.println(1 + (2 << 3));
        System.out.println(6 & 3 + 1);
        System.out.println(6 | 1 << 3);
        System.out.println(-17 >> 2);
        System.out.println(-17 / 4);
        System.out.println(-17 >>> 30);
    }
}
